// Bundles the agent's core (the same tools and instructions as in the browser) for the agent-run function.
// fflate (for Word files) and pdf-lib (for filling the agencies' forms) are loaded from npm by Deno at run time. The two
// agency PDFs kept with the code (src/forms/pdf, the SS-4 and CBP 5106) go inside the bundle, as the app has them, so the
// server fills them without fetching anything; the rest it fetches from the site's /app/forms/ (agent-run formPdf).
import { build } from "esbuild";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
const inlinePdf = {
  name: "inline-pdf",
  setup(b) {
    b.onResolve({ filter: /\.pdf\?inline$/ }, (a) => ({ path: resolve(a.resolveDir, a.path.replace(/\?inline$/, "")), namespace: "inline-pdf" }));
    b.onLoad({ filter: /.*/, namespace: "inline-pdf" }, async (a) => ({ contents: `export default ${JSON.stringify("data:application/pdf;base64," + (await readFile(a.path)).toString("base64"))};`, loader: "js" }));
  },
};
await build({
  entryPoints: ["src/server/agent-entry.ts"],
  bundle: true, format: "esm", platform: "neutral", target: "es2022", minify: true, legalComments: "none",
  mainFields: ["module", "main"],
  alias: { fflate: "npm:fflate@0.8.3", "pdf-lib": "npm:pdf-lib@1.17.1" },
  external: ["npm:*", "thinking-orbs"], plugins: [inlinePdf],
  banner: { js: "// Generated by scripts/build-agent.mjs from src/. Do not edit." },
  outfile: "supabase/functions/agent-run/agent.js",
});
console.log("built supabase/functions/agent-run/agent.js");
