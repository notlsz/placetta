// Writes src/inspections/index.ts from the per-city guides in src/inspections/data/*.json.
import { readdirSync, writeFileSync } from "node:fs";
const dir = new URL("../src/inspections/", import.meta.url);
const ids = readdirSync(new URL("data/", dir)).filter(f => f.endsWith(".json")).map(f => f.slice(0, -5)).sort();
const v = (id) => "g_" + id.replace(/\W/g, "_");
writeFileSync(new URL("index.ts", dir), `// Generated by scripts/build-inspections.mjs from data/*.json. Do not edit by hand.
import type { LocalInspections } from "./types";
${ids.map(id => `import ${v(id)} from "./data/${id}.json";`).join("\n")}

/** Each city's inspections and how to pass them, by the forms library's place code (SJ, SF, NYC, ...). */
export const INSPECTIONS: Record<string, LocalInspections> = {
${ids.map(id => `  "${id}": ${v(id)} as LocalInspections,`).join("\n")}
};
`);
console.log(`inspections: ${ids.length} (${ids.join(", ")})`);
