#!/usr/bin/env python3
"""Turns the line-by-line research (one JSON file per batch, written from the agencies' own forms and pages) into
src/forms/lines.ts, which the forms library applies over its entries. Run: python3 scripts/build-lines.py <dir>

Only official sources go in. A form whose research found nothing keeps its library entry as it was."""
import json, re, sys, glob, os

src = sys.argv[1] if len(sys.argv) > 1 else "research/lines"
out = {}
for path in sorted(glob.glob(os.path.join(src, "b*.json"))):
    if path.endswith("-urls.json"):
        continue
    for fid, v in json.load(open(path)).items():
        if v.get("status") not in ("mapped", "page_only"):
            continue
        fields, seen = [], set()
        for f in v.get("fields", [])[:40]:
            fid_ = re.sub(r"[^a-z0-9_]", "_", str(f.get("id") or "").lower()).strip("_")[:40] or f"l{len(fields)+1}"
            while fid_ in seen:
                fid_ += "_2"
            seen.add(fid_)
            en, zh = str(f.get("en", "")).strip()[:120], str(f.get("zh", "")).strip()[:120]
            if not en:
                continue
            row = {"id": fid_, "line": str(f.get("line", "") or "")[:24], "label": {"en": en, "zh": zh or en}}
            if f.get("options"):
                row["options"] = [str(o)[:80] for o in f["options"]][:12]
            if f.get("hint_en"):
                row["hint"] = {"en": str(f["hint_en"])[:200], "zh": str(f.get("hint_zh") or f["hint_en"])[:200]}
            fields.append(row)
        attach = [{"en": str(a.get("en", ""))[:200], "zh": str(a.get("zh") or a.get("en", ""))[:200]} for a in v.get("attach", []) if a.get("en")][:15]
        sources = [s["url"] for s in v.get("sources", []) if isinstance(s, dict) and str(s.get("url", "")).startswith("http")][:4]
        d = v.get("destination") or {}
        dest = {k: d[k] for k in ("email", "fax", "portal") if d.get(k)}
        if isinstance(d.get("mail"), dict) and d["mail"].get("line1"):
            dest["mail"] = {k: d["mail"][k] for k in ("name", "line1", "line2", "city", "state", "zip") if d["mail"].get(k)}
        out[fid] = {
            "status": v["status"], "seen": str(v.get("form_seen", ""))[:160], "read": str(v.get("read_on", ""))[:10],
            "sources": sources, "fields": fields, "attach": attach,
            "submit": {**dest, "signature": d.get("signature", "unknown"), "evidence": str(d.get("evidence", ""))[:400], "source": d.get("source", "")},
            "notes": str(v.get("notes", ""))[:1200],
        }

body = json.dumps(out, ensure_ascii=False, indent=1)
ts = f"""// Generated by scripts/build-lines.py from the line-by-line research of each agency's own form. Do not edit by hand:
// fix the research and run it again. Each entry: the questions as the form (or, for "page_only", the agency's
// "what you'll need" page) prints them, the attachments it lists, and how it is submitted, with the sources read.
import type {{ Bi }} from "../bi";
import type {{ FormField }} from "./registry";

export type Lines = {{
  status: "mapped" | "page_only"; seen: string; read: string; sources: string[]; fields: FormField[]; attach: Bi[];
  submit: {{ email?: string; fax?: string; portal?: string; mail?: Record<string, string>; signature: string; evidence: string; source: string }};
  notes: string;
}};

export const LINES: Record<string, Lines> = {body};
"""
open("src/forms/lines.ts", "w").write(ts)
print(f"{len(out)} forms, {sum(len(x['fields']) for x in out.values())} lines")
