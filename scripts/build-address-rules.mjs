// Writes src/forms/address-rules/index.ts from the per-form research in src/forms/address-rules/<form>.json, and holds
// every rule to the bar the product promises: a rule other than "unconfirmed" needs at least three official sources
// that agree (three different pages). A rule with fewer is written as "unconfirmed", so Placetta treats the line as
// needing a US address and asks the agency. Field ids must be the form map's own answer ids.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
const dir = new URL("../src/forms/address-rules/", import.meta.url);
const maps = new URL("../src/forms/maps/", import.meta.url);
const RULES = ["in_state_street", "local_premises", "us_street", "us_any", "foreign_ok", "unconfirmed"];
const ids = readdirSync(dir).filter(f => f.endsWith(".json")).map(f => f.slice(0, -5)).sort();
const warn = [];
let fields = 0, confirmed = 0;
for (const id of ids) {
  const file = new URL(`${id}.json`, dir), d = JSON.parse(readFileSync(file, "utf8"));
  if (d.form !== id) warn.push(`${id}: "form" says ${d.form}`);
  const map = existsSync(new URL(`${id}.json`, maps)) ? JSON.parse(readFileSync(new URL(`${id}.json`, maps), "utf8")) : null;
  let changed = false;
  for (const [f, r] of Object.entries(d.fields ?? {})) {
    fields++;
    if (map && !(f in map.boxes)) warn.push(`${id}.${f}: not an answer id in the form's map`);
    if (!RULES.includes(r.rule)) { warn.push(`${id}.${f}: unknown rule ${r.rule}`); r.rule = "unconfirmed"; changed = true; }
    if (!r.what?.en || !r.what?.zh || !r.ifNone?.en || !r.ifNone?.zh) warn.push(`${id}.${f}: missing what/ifNone in a language`);
    const urls = new Set((r.confirmations ?? []).filter(c => /^https?:\/\//.test(c.url) && c.quote).map(c => c.url.replace(/#.*$/, "").replace(/\/$/, "")));
    if (r.rule !== "unconfirmed" && urls.size < 3) { warn.push(`${id}.${f}: ${r.rule} has ${urls.size} source(s), written as unconfirmed`); r.rule = "unconfirmed"; changed = true; }
    if (r.rule !== "unconfirmed") confirmed++;
  }
  if (changed) writeFileSync(file, JSON.stringify(d, null, 2) + "\n");
}
const v = (id) => "r_" + id.replace(/\W/g, "_");
writeFileSync(new URL("index.ts", dir), `// Generated by scripts/build-address-rules.mjs from ./<form>.json. Do not edit by hand.
import type { FormAddressRules } from "../addressRules";
${ids.map(id => `import ${v(id)} from "./${id}.json";`).join("\n")}

/** What each address line on a form must hold, by form id and answer id, each rule confirmed by three official sources. */
export const ADDRESS_RULES: Record<string, FormAddressRules> = {
${ids.map(id => `  "${id}": ${v(id)} as FormAddressRules,`).join("\n")}
};
`);
console.log(`address rules: ${ids.length} forms, ${fields} address lines, ${confirmed} confirmed by 3+ sources, ${fields - confirmed} unconfirmed`);
if (warn.length) console.log(warn.map(w => "  " + w).join("\n"));
