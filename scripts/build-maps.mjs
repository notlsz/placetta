// Writes src/forms/maps/index.ts from the box maps in src/forms/maps/*.json (one per form Placetta fills by map).
import { readdirSync, writeFileSync } from "node:fs";
const dir = new URL("../src/forms/maps/", import.meta.url);
const ids = readdirSync(dir).filter(f => f.endsWith(".json")).map(f => f.slice(0, -5)).sort();
const v = (id) => "m_" + id.replace(/\W/g, "_");
writeFileSync(new URL("index.ts", dir), `// Generated by scripts/build-maps.mjs from the JSON files here. Do not edit by hand.
import type { FormMap } from "../boxes";
${ids.map(id => `import ${v(id)} from "./${id}.json";`).join("\n")}

export const MAPS: Record<string, FormMap> = {
${ids.map(id => `  "${id}": ${v(id)} as FormMap,`).join("\n")}
};
`);
console.log(`maps: ${ids.length} (${ids.join(", ")})`);
