"""Records every scripted reply with a natural neural voice (Kokoro: af_heart in English, zf_xiaoxiao in Chinese)
and writes src/voices.generated.ts, keyed by language + FNV-1a hash of the reply text.

    npx esbuild scripts/dump-replies.ts --bundle --platform=node --format=esm --outfile=/tmp/dump.mjs && node /tmp/dump.mjs > replies.json
    python3 scripts/make-voices.py replies.json /path/to/kokoro-v1.0.int8.onnx /path/to/voices-v1.0.bin
"""
import base64, json, os, re, subprocess, sys, tempfile
import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

def fnv(s: str) -> str:
    h = 2166136261
    for ch in s:
        h ^= ord(ch); h = (h * 16777619) & 0xFFFFFFFF
    return format(h, "08x")

# spoken forms only; the keys stay the text on screen
SAY = {
    "zh": [(r"EIN", "雇主识别号"), (r"\$([\d,]+)", lambda m: m.group(1).replace(",", "") + "美元")],
    "en": [(r"\bEIN\b", "E.I.N."), (r"\bEDD\b", "E.D.D."), (r"\bLLC\b", "L.L.C."), (r"\bOK\b", "okay")],
}
D = "零一二三四五六七八九"
def zh_num(n: int) -> str:
    """Spoken Chinese for 0 to 9999: 1385 -> 一千三百八十五, 410 -> 四百一十, 21 -> 二十一."""
    if n < 10: return D[n]
    if n < 20: return "十" + (D[n % 10] if n % 10 else "")
    out, zero = "", False
    for unit, v in (("千", 1000), ("百", 100), ("十", 10), ("", 1)):
        d = n // v % 10
        if d: out += ("零" if zero and out else "") + D[d] + unit; zero = False
        elif out: zero = True
    return out

def zh_digits(s: str) -> str:
    s = re.sub(r"(?<![\d])2(?=\s*[项张名个周份])", "两", s)
    s = re.sub(r"\d+", lambda m: zh_num(int(m.group())), s)
    return re.sub(r"(?<=[\u4e00-\u9fff])\s+|\s+(?=[\u4e00-\u9fff])", "", s)

# a short breath between sentences, the way a person reads a message aloud
GAP = {"en": 0.24, "zh": 0.2}
SPLIT = re.compile(r"(?<=[.!?;:。！？；：])\s*")

def speak(k, g2p, lang, text):
    parts = [p for p in SPLIT.split(text) if p.strip()]
    out, sr = [], 24000
    for p in parts:
        if lang == "zh":
            samples, sr = k.create(g2p(p), voice="zf_xiaoxiao", speed=1.0, is_phonemes=True)
        else:
            samples, sr = k.create(p, voice="af_heart", speed=1.0, lang="en-us")
        out += [samples, np.zeros(int(sr * GAP[lang]), dtype=samples.dtype)]
    return np.concatenate(out[:-1]), sr

def main(replies, model, voices):
    k = Kokoro(model, voices)
    g2p = None
    out = {}
    for lang, text in json.load(open(replies)):
        say = text
        for a, b in SAY[lang]: say = re.sub(a, b, say)
        if lang == "zh": say = zh_digits(say)
        if lang == "zh" and g2p is None:
            from misaki import zh; g2p = zh.ZHG2P()
        samples, sr = speak(k, g2p, lang, say)
        with tempfile.TemporaryDirectory() as d:
            w, m = os.path.join(d, "a.wav"), os.path.join(d, "a.mp3")
            sf.write(w, samples, sr)
            subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", w, "-af", "afade=t=in:d=0.02", "-ac", "1", "-b:a", "40k", m], check=True)
            out[f"{lang}:{fnv(text)}"] = "data:audio/mpeg;base64," + base64.b64encode(open(m, "rb").read()).decode()
        print(lang, round(len(samples) / sr, 1), "s", text[:50], file=sys.stderr)
    src = "// Generated by scripts/make-voices.py: every scripted reply, recorded with a natural neural voice.\n"
    src += "export const CLIPS: Record<string, string> = " + json.dumps(out, indent=0) + ";\n"
    open(os.path.join(os.path.dirname(__file__), "..", "src", "voices.generated.ts"), "w").write(src)
    print("clips", len(out), "bytes", len(src), file=sys.stderr)

if __name__ == "__main__":
    main(*sys.argv[1:4])
