/* Files the workspace can hand you: receipts, filled applications, document placeholders, the audit trail.
   In the shared preview they go through the viewer's download prompt; anywhere else, a normal browser download. */

type Downloads = { save(r: { filename: string; data: Blob | string }): Promise<{ status: string }> };
type ClaudeWin = { claude?: { use?: (n: string) => Promise<unknown> } };
let dl: Promise<Downloads | null> | null = null;
/** Ask the viewer for the downloads capability once; null outside a viewer or when it isn't served. */
export const downloads = () => {
  const c = (window as unknown as ClaudeWin).claude;
  if (!c?.use) return Promise.resolve(null);
  return (dl ??= c.use("downloads").then(x => (x as Downloads) ?? null, () => null));
};

export async function saveFile(filename: string, data: Blob): Promise<"saved" | "declined" | "unavailable"> {
  const ns = await downloads();
  if (ns) {
    try { await ns.save({ filename, data }); return "saved"; }
    catch (e) { const code = (e as { code?: string })?.code; if (code === "declined" || code === "rate_limited") return "declined"; }
  }
  try {
    const url = URL.createObjectURL(data), a = document.createElement("a");
    a.href = url; a.download = filename; a.rel = "noopener"; document.body.appendChild(a); a.click(); a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 5000);
    return "saved";
  } catch { return "unavailable"; }
}

/* ------------------------------ tiny PDF ------------------------------ */

const ascii = (s: string) => s.replace(/[•]/g, "*").replace(/[×]/g, "x").replace(/[–—]/g, "-").replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[^\x20-\x7E]/g, "");
const esc = (s: string) => ascii(s).replace(/[\\()]/g, m => "\\" + m);
function wrap(s: string, n: number) {
  const out: string[] = []; let line = "";
  for (const w of ascii(s).split(/\s+/)) { if ((line + " " + w).trim().length > n) { if (line) out.push(line); line = w; } else line = (line + " " + w).trim(); }
  if (line) out.push(line);
  return out.length ? out : [""];
}

/** A one-page Letter PDF in Helvetica: a title, a subtitle, label/value rows and notes. ASCII text only. */
export function pdf(title: string, sub: string, rows: [string, string][], notes: string[] = []): Blob {
  const ops: string[] = [];
  const text = (x: number, y: number, size: number, bold: boolean, s: string, gray = 0) => ops.push(`BT ${gray} g /${bold ? "F2" : "F1"} ${size} Tf ${x} ${y} Td (${esc(s)}) Tj ET`);
  // header band
  ops.push("0.894 0.937 0.984 rg 0 742 612 50 re f");
  text(56, 760, 11, true, "PLACETTA", 0.25);
  text(400, 760, 9, false, "SAMPLE - NOT AN OFFICIAL DOCUMENT", 0.4);
  let y = 700;
  text(56, y, 18, true, title); y -= 20;
  for (const l of wrap(sub, 90)) { text(56, y, 10, false, l, 0.4); y -= 14; }
  y -= 14;
  ops.push(`0.85 G 56 ${y + 6} m 556 ${y + 6} l S`);
  y -= 12;
  for (const [k, v] of rows) {
    const vs = wrap(v || "-", 58);
    text(56, y, 10, true, k);
    vs.forEach((l, i) => text(230, y - i * 14, 10, false, l));
    y -= 14 * vs.length + 8;
    if (y < 120) break;
  }
  y -= 10;
  for (const n of notes) for (const l of wrap(n, 95)) { if (y < 80) break; text(56, y, 9, false, l, 0.35); y -= 13; }
  text(56, 48, 8, false, "Generated by the Placetta sample workspace. Made-up data for demonstration; not filed with any agency.", 0.5);
  const stream = ops.join("\n");
  const objs = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
  ];
  let out = "%PDF-1.4\n";
  const offs: number[] = [];
  objs.forEach((o, i) => { offs.push(out.length); out += `${i + 1} 0 obj\n${o}\nendobj\n`; });
  const xref = out.length;
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + offs.map(o => String(o).padStart(10, "0") + " 00000 n \n").join("");
  out += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return new Blob([out], { type: "application/pdf" });
}

/* ------------------------------ documents ------------------------------ */

const conf = (s: string) => { let h = 7; for (const c of s) h = (h * 31 + c.charCodeAt(0)) >>> 0; return "PL-" + h.toString(36).toUpperCase().slice(0, 8); };
const total = (a: Application) => a.fees.reduce((s, f) => s + f.amount, 0);

export function applicationPdf(a: Application): Blob {
  return pdf(a.name.en, `${a.form?.en ?? "Application"}. ${a.agency.en}. Filled by Placetta from your workspace.`,
    a.fields.map(f => [f.label.en, f.value || "(not yet)"] as [string, string]),
    [`Fee: ${total(a) ? money(total(a)) : "No fee"}. ${a.feeNote?.en ?? ""}`, `Source: ${a.source.url}`]);
}

export function docBlob(d: Doc, w: Workspace): { name: string; blob: Blob } {
  const app = d.app ? w.apps.find(a => a.id === d.app) : undefined;
  const base = d.name.replace(/\.[^.]+$/, "");
  if (d.tag.en === "Receipt" && app) {
    const paid = total(app);
    return { name: d.name, blob: pdf(`Receipt: ${app.name.en}`, `${app.agency.en}. Submitted by Placetta for Moonleaf Tea LLC.`, [
      ["Confirmation", conf(d.id)], ["Submitted", fmtStamp(d.at)], ["Application", app.name.en], ["Agency", app.agency.en],
      ["Amount paid", paid ? money(paid) : "No fee"], ["Paid with", paid ? "Card ending 4821" : "-"], ["Status", "Received, in review"],
    ], ["Keep this receipt with your records. Placetta watches the agency for a decision."]) };
  }
  if (app && d.by === "agent") return { name: base + ".pdf", blob: applicationPdf(app) };
  return { name: base + ".pdf", blob: pdf(d.name, "Placeholder for a sample document in the Placetta demo workspace.", [
    ["File", d.name], ["Added", fmtStamp(d.at)], ["Added by", d.by === "you" ? "You" : d.by === "agent" ? "Placetta" : "Agency"], ...(app ? [["Used for", app.name.en] as [string, string]] : []),
  ], ["The real file would be stored here. In this sample, the content is a stand-in."]) };
}

export function auditCsv(rows: Audit[]): Blob {
  const q = (s: string) => `"${s.replace(/"/g, '""')}"`;
  const by = (a: Audit) => (a.actor === "agent" ? "Placetta" : a.actor === "you" ? "You" : a.who?.en ?? "Agency");
  const lines = [["Time", "By", "Action", "On", "Details"].map(q).join(","), ...rows.map(a => [fmtStamp(a.at), by(a), a.action.en, a.object.en, a.detail?.en ?? ""].map(q).join(","))];
  return new Blob(["﻿" + lines.join("\r\n")], { type: "text/csv" });
}
