const ascii = (s: string) => s.replace(/[•]/g, "*").replace(/[×]/g, "x").replace(/[–—]/g, "-").replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[^\x20-\x7E]/g, "");
const esc = (s: string) => ascii(s).replace(/[\\()]/g, m => "\\" + m);
function wrap(s: string, n: number) {
  const out: string[] = []; let line = "";
  for (const w of ascii(s).split(/\s+/)) { if ((line + " " + w).trim().length > n) { if (line) out.push(line); line = w; } else line = (line + " " + w).trim(); }
  if (line) out.push(line);
  return out.length ? out : [""];
}

/** A one-page Letter PDF in Helvetica: a title, a subtitle, label/value rows and notes. ASCII text only. */
export function pdf(title: string, sub: string, rows: [string, string][], notes: string[] = [], mark = "SAMPLE - NOT AN OFFICIAL DOCUMENT"): Blob {
  const ops: string[] = [];
  const text = (x: number, y: number, size: number, bold: boolean, s: string, gray = 0) => ops.push(`BT ${gray} g /${bold ? "F2" : "F1"} ${size} Tf ${x} ${y} Td (${esc(s)}) Tj ET`);
  // header band
  ops.push("0.894 0.937 0.984 rg 0 742 612 50 re f");
  text(56, 760, 11, true, "PLACETTA", 0.25);
  text(612 - 56 - mark.length * 4.6, 760, 9, false, mark, 0.4);
  let y = 700;
  text(56, y, 18, true, title); y -= 20;
  for (const l of wrap(sub, 90)) { text(56, y, 10, false, l, 0.4); y -= 14; }
  y -= 14;
  ops.push(`0.85 G 56 ${y + 6} m 556 ${y + 6} l S`);
  y -= 12;
  for (const [k, v] of rows) {
    const vs = wrap(v || "-", 58);
    text(56, y, 10, true, k);
    vs.forEach((l, i) => text(230, y - i * 14, 10, false, l));
    y -= 14 * vs.length + 8;
    if (y < 120) break;
  }
  y -= 10;
  for (const n of notes) for (const l of wrap(n, 95)) { if (y < 80) break; text(56, y, 9, false, l, 0.35); y -= 13; }
  text(56, 48, 8, false, "Generated by the Placetta sample workspace. Made-up data for demonstration; not filed with any agency.", 0.5);
  const stream = ops.join("\n");
  const objs = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
  ];
  let out = "%PDF-1.4\n";
  const offs: number[] = [];
  objs.forEach((o, i) => { offs.push(out.length); out += `${i + 1} 0 obj\n${o}\nendobj\n`; });
  const xref = out.length;
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + offs.map(o => String(o).padStart(10, "0") + " 00000 n \n").join("");
  out += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return new Blob([out], { type: "application/pdf" });
}

/* ------------------------------ documents ------------------------------ */

const conf = (s: string) => { let h = 7; for (const c of s) h = (h * 31 + c.charCodeAt(0)) >>> 0; return "PL-" + h.toString(36).toUpperCase().slice(0, 8); };
const total = (a: Application) => a.fees.reduce((s, f) => s + f.amount, 0);

export function applicationPdf(a: Application): Blob {
  return pdf(`Your answers: ${a.name.en}`, `For ${a.form?.en ?? "the application"}, ${a.agency.en}. Enter these on the agency's own form, line by line.`,
    a.fields.map(f => [f.label.en, f.value || "(not yet)"] as [string, string]),
    [`Fee: ${a.fees.some(f => f.tbd) ? "set by the agency" : total(a) ? money(total(a)) : "No fee"}. ${a.feeNote?.en ?? ""}`, `File it on the agency's site: ${a.source.url}`],
    "ANSWER SHEET - FILE ON THE AGENCY'S OWN FORM");
}

export function docBlob(d: Doc, w: Workspace): { name: string; blob: Blob } {
  const app = d.app ? w.apps.find(a => a.id === d.app) : undefined;
  const base = d.name.replace(/\.[^.]+$/, "");
  if (d.tag.en === "Receipt" && app) {
    const paid = total(app);
    return { name: d.name, blob: pdf(`Receipt: ${app.name.en}`, `${app.agency.en}. Submitted by Placetta for Moonleaf Tea LLC.`, [
      ["Confirmation", conf(d.id)], ["Submitted", fmtStamp(d.at)], ["Application", app.name.en], ["Agency", app.agency.en],
      ["Amount paid", paid ? money(paid) : "No fee"], ["Paid by", paid ? "You, on the agency's own payment page" : "-"], ["Status", "Received, in review"],
    ], ["Keep this receipt with your records. Placetta watches the agency for a decision."]) };
  }
  if (app && d.by === "agent") return { name: base + ".pdf", blob: applicationPdf(app) };
  return { name: base + ".pdf", blob: pdf(d.name, "Placeholder for a sample document in the Placetta demo workspace.", [
    ["File", d.name], ["Added", fmtStamp(d.at)], ["Added by", d.by === "you" ? "You" : d.by === "agent" ? "Placetta" : "Agency"], ...(app ? [["Used for", app.name.en] as [string, string]] : []),
  ], ["The real file would be stored here. In this sample, the content is a stand-in."]) };
}

/** One CSV cell: quoted, quotes doubled, and a leading = + - @ (or tab, return) made inert so a spreadsheet shows the
 *  text instead of running it as a formula (audit cells hold names and messages people typed). */
export function csvCell(v: unknown): string {
  let s = v === null || v === undefined ? "" : String(v);
  if (/^[=+\-@\t\r]/.test(s)) s = "'" + s;
  return `"${s.replace(/"/g, '""')}"`;
}
/** The audit trail an owner or admin exports from the server (audit_export): every entry, oldest first, UTC times. */
export type AuditExportRow = {
  id: number; created_at: string; actor: string; actor_email: string | null; action_en: string; action_zh: string | null;
  object_en: string | null; object_zh: string | null; detail_en: string | null; detail_zh: string | null;
};
export const AUDIT_EXPORT_HEADER = ["Time (UTC)", "Entry", "By", "Person", "Action", "On", "Details", "Action (Chinese)", "On (Chinese)", "Details (Chinese)"];
const BY: Record<string, string> = { you: "Workspace member", agent: "Placetta (Odelia)", team: "Placetta team", agency: "Agency", idp: "Identity provider (SCIM)" };
export function auditExportCsv(rows: AuditExportRow[]): string {
  const lines = [AUDIT_EXPORT_HEADER.map(csvCell).join(","), ...rows.map(r => [
    new Date(r.created_at).toISOString(), r.id, BY[r.actor] ?? r.actor, r.actor_email ?? "", r.action_en, r.object_en ?? "", r.detail_en ?? "",
    r.action_zh ?? "", r.object_zh ?? "", r.detail_zh ?? "",
  ].map(csvCell).join(","))];
  return "﻿" + lines.join("\r\n") + "\r\n";
}

export function auditCsv(rows: Audit[]): Blob {
  const q = (s: string) => `"${s.replace(/"/g, '""')}"`;
  const by = (a: Audit) => (a.actor === "agent" ? "Placetta" : a.actor === "you" ? "You" : a.who?.en ?? "Agency");
  const lines = [["Time", "By", "Action", "On", "Details"].map(q).join(","), ...rows.map(a => [fmtStamp(a.at), by(a), a.action.en, a.object.en, a.detail?.en ?? ""].map(q).join(","))];
  return new Blob(["﻿" + lines.join("\r\n")], { type: "text/csv" });
}

/* ------------------------------ Word documents ------------------------------ */

const xml = (s: string) => s.replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!).replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "");
const run = (t: string, bold = false, size?: number) =>
  `<w:r><w:rPr>${bold ? "<w:b/>" : ""}${size ? `<w:sz w:val="${size}"/>` : ""}<w:rFonts w:ascii="Calibri" w:hAnsi="Calibri" w:eastAsia="Microsoft YaHei"/></w:rPr><w:t xml:space="preserve">${xml(t)}</w:t></w:r>`;
/** **bold** spans inside a line. */
const runs = (line: string, size?: number) => line.split(/(\*\*[^*]+\*\*)/).filter(Boolean).map(p => (p.startsWith("**") && p.endsWith("**") ? run(p.slice(2, -2), true, size) : run(p, false, size))).join("");
const para = (body: string, o: { space?: number; indent?: boolean } = {}) =>
  `<w:p><w:pPr><w:spacing w:after="${o.space ?? 160}"/>${o.indent ? '<w:ind w:left="360" w:hanging="240"/>' : ""}</w:pPr>${body}</w:p>`;

/** A real .docx from simple text: "# " and "## " headings, "- " bullets, **bold**, blank lines between paragraphs. Opens in Word, Pages and Google Docs. */
export async function docx(title: string, text: string): Promise<Blob> {
  const { zipSync, strToU8 } = await import("fflate");
  const body: string[] = [para(run(title, true, 32), { space: 240 })];
  for (const raw of text.replace(/\r\n?/g, "\n").split("\n")) {
    const line = raw.trimEnd();
    if (!line.trim()) continue;
    if (/^#\s/.test(line)) body.push(para(run(line.replace(/^#\s+/, ""), true, 28), { space: 200 }));
    else if (/^##+\s/.test(line)) body.push(para(run(line.replace(/^#+\s+/, ""), true, 24), { space: 120 }));
    else if (/^\s*[-*•]\s/.test(line)) body.push(para(run("•  ") + runs(line.replace(/^\s*[-*•]\s+/, "")), { space: 80, indent: true }));
    else body.push(para(runs(line)));
  }
  const files = {
    "[Content_Types].xml": `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>`,
    "_rels/.rels": `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>`,
    "word/document.xml": `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>${body.join("")}<w:sectPr><w:pgSz w:w="12240" w:h="15840"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440" w:header="720" w:footer="720" w:gutter="0"/></w:sectPr></w:body></w:document>`,
  };
  const zipped = zipSync(Object.fromEntries(Object.entries(files).map(([k, v]) => [k, strToU8(v)])), { level: 6 });
  return new Blob([zipped as BlobPart], { type: "application/vnd.openxmlformats-officedocument.wordprocessingml.document" });
}
